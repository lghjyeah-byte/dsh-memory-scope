import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { MemoryStore } from '../store.js';
import { apply } from '../index.js';
const root = path.resolve('tests/dsh-native-memory-fixture');
fs.mkdirSync(root, { recursive: true });
const file = path.join(root, 'memory.json');
if (fs.existsSync(file)) fs.unlinkSync(file);
const store = new MemoryStore(file);
store.create('office', '办公'); store.create('friends', '朋友');
store.setSummary('office', '办公专用偏好'); store.setSummary('friends', '好友专用偏好');
store.bind('office-session', 'office'); store.bind('friend-session', 'friends');
assert.equal(store.forSession('office-session').summary, '办公专用偏好');
assert.equal(store.forSession('friend-session').summary, '好友专用偏好');
assert.equal(store.forSession('group-session'), null);
assert.throws(() => store.create('__proto__', '坏名称'));
const officeRoot = path.join(root, 'office-workspace');
store.bindWorkspace(officeRoot, 'office');
assert.equal(store.forSession('new-office', path.join(officeRoot, 'project')).summary, '办公专用偏好');
assert.equal(store.forSession('other-chat', path.join(root, 'other')), null);
assert.equal(store.forSession('friend-session', officeRoot).summary, '好友专用偏好');
store.unbind('friend-session');
assert.equal(store.forSession('friend-session', officeRoot), null);
assert.throws(() => store.bind('friend-session', 'office'), /新会话/);
store.bind('friend-session', 'friends');
const listeners = new Map();
function agent(id) { return { id, status: 'idle', session: { header: {} }, ctx: { on(name, cb) { listeners.set(id + ':' + name, cb); return () => listeners.delete(id + ':' + name); } } }; }
const agents = [agent('office-session'), agent('friend-session'), agent('group-session')];
let route;
const ctx = { get: name => name === 'dshHomePath' ? (() => file) : undefined, agents: { roots: () => agents, get: id => agents.find(a => a.id === id) }, webServer: { register: x => { route = x; return () => {}; } }, on: () => () => {}, effect(fn) { return fn(); } };
apply(ctx);
async function message(id) { return listeners.get(id + ':agent/pre-step')({ step: 1, signal: new AbortController().signal }, async () => ({ kind: 'enter', messages: [{ role: 'user', content: [] }] })); }
const office = await message('office-session');
const group = await message('group-session');
assert.match(JSON.stringify(office), /办公专用偏好/);
assert.doesNotMatch(JSON.stringify(office), /好友专用偏好/);
assert.equal(group.messages.length, 1);
assert.ok(route && route.path === '/api/dsh-memory-scope');
console.log('范围绑定、未绑定不注入、不同会话隔离：通过');
